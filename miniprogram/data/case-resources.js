function defineSkill(id, title, description, instructions) {
  return {
    id,
    title,
    description,
    markdown: ['---', `name: ${id}`, `description: ${JSON.stringify(description)}`, '---', '', `# ${title}`, '', ...instructions, ''].join('\n')
  }
}

